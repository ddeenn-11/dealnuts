import { openDB } from 'idb'

const DB_NAME = 'buyright-db'
const DB_VERSION = 1
const ENTRY_STORE = 'entries'
const GROUP_STORE = 'groups'

let dbPromise = null

function getDb() {
  if (!dbPromise) {
    dbPromise = openDB(DB_NAME, DB_VERSION, {
      upgrade(db) {
        if (!db.objectStoreNames.contains(ENTRY_STORE)) {
          const entryStore = db.createObjectStore(ENTRY_STORE, { keyPath: 'id' })
          entryStore.createIndex('dateAdded', 'dateAdded')
        }
        if (!db.objectStoreNames.contains(GROUP_STORE)) {
          db.createObjectStore(GROUP_STORE, { keyPath: 'id' })
        }
      },
    })
  }
  return dbPromise
}

function makeId() {
  return `${Date.now()}-${Math.random().toString(36).slice(2, 9)}`
}

// ---------- Entries ----------

export async function addEntry(entry) {
  const db = await getDb()
  const record = {
    id: makeId(),
    dateAdded: Date.now(), // immutable — set once, never overwritten by updateEntry
    manualGroupIds: [],
    ...entry,
  }
  await db.add(ENTRY_STORE, record)
  return record
}

export async function updateEntry(id, changes) {
  const db = await getDb()
  const existing = await db.get(ENTRY_STORE, id)
  if (!existing) return null
  const { dateAdded, id: _ignoredId, ...safeChanges } = changes
  const updated = { ...existing, ...safeChanges, id: existing.id, dateAdded: existing.dateAdded }
  await db.put(ENTRY_STORE, updated)
  return updated
}

export async function deleteEntry(id) {
  const db = await getDb()
  await db.delete(ENTRY_STORE, id)
  // also detach from any manual groups
  const groups = await db.getAll(GROUP_STORE)
  await Promise.all(
    groups
      .filter((g) => g.entryIds.includes(id))
      .map((g) => {
        g.entryIds = g.entryIds.filter((eid) => eid !== id)
        return db.put(GROUP_STORE, g)
      })
  )
}

export async function getAllEntries() {
  const db = await getDb()
  const all = await db.getAll(ENTRY_STORE)
  return all.sort((a, b) => b.dateAdded - a.dateAdded)
}

export async function getEntry(id) {
  const db = await getDb()
  return db.get(ENTRY_STORE, id)
}

// ---------- Manual groups ----------

export async function createGroup(name) {
  const db = await getDb()
  const group = { id: makeId(), name: name.trim(), isAutoGenerated: false, entryIds: [] }
  await db.add(GROUP_STORE, group)
  return group
}

export async function getAllGroups() {
  const db = await getDb()
  return db.getAll(GROUP_STORE)
}

export async function addEntryToGroup(groupId, entryId) {
  const db = await getDb()
  const group = await db.get(GROUP_STORE, groupId)
  if (!group) return null
  if (!group.entryIds.includes(entryId)) {
    group.entryIds.push(entryId)
    await db.put(GROUP_STORE, group)
  }
  return group
}

export async function removeEntryFromGroup(groupId, entryId) {
  const db = await getDb()
  const group = await db.get(GROUP_STORE, groupId)
  if (!group) return null
  group.entryIds = group.entryIds.filter((id) => id !== entryId)
  await db.put(GROUP_STORE, group)
  return group
}

export async function deleteGroup(groupId) {
  const db = await getDb()
  await db.delete(GROUP_STORE, groupId)
}

